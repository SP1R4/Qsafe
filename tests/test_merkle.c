static void mk_leaves(unsigned char leaves[8][32]) {
    for (int i = 0; i < 8; i++) { char d[8]; int n = snprintf(d, sizeof d, "leaf%d", i);
        merkle_hash_leaf((const unsigned char *)d, (size_t)n, leaves[i]); }
}

int main(void) {
    unsigned char leaves[8][32];
    mk_leaves(leaves);

    /* 1. Roots for n=1..8 match the independent implementation. */
    int roots_ok = 1;
    for (size_t n = 1; n <= 8; n++) {
        unsigned char r[32]; merkle_root(leaves, n, r);
        if (memcmp(r, ROOTS[n - 1], 32) != 0) roots_ok = 0;
    }
    CHECK(roots_ok, "roots n=1..8 match RFC 6962 reference (KAT)");

    unsigned char er[32]; merkle_root(leaves, 0, er);
    CHECK(memcmp(er, EMPTY, 32) == 0, "empty tree = SHA-256(\"\")");

    /* 2. Inclusion proof KAT (m=3, n=8) matches the reference, verifies, tampers fail. */
    unsigned char proof[MERKLE_MAX_PROOF][32]; size_t plen;
    CHECK(merkle_inclusion_proof(leaves, 8, 3, proof, &plen) == 0 && plen == 3, "inclusion proof m=3 n=8 built");
    int incl_kat = (plen == 3);
    for (size_t i = 0; i < plen && incl_kat; i++) if (memcmp(proof[i], INCL[i], 32) != 0) incl_kat = 0;
    CHECK(incl_kat, "inclusion proof matches reference");
    CHECK(merkle_verify_inclusion(3, 8, leaves[3], INCL, 3, ROOTS[7]) == 1, "verify reference inclusion proof");

    /* 3. Every leaf of an 8-leaf tree has a verifying inclusion proof; tampering fails. */
    int all_incl = 1, tamper_leaf = 0, tamper_proof = 0, wrong_idx = 0;
    unsigned char root8[32]; merkle_root(leaves, 8, root8);
    for (size_t m = 0; m < 8; m++) {
        merkle_inclusion_proof(leaves, 8, m, proof, &plen);
        if (!merkle_verify_inclusion(m, 8, leaves[m], proof, plen, root8)) all_incl = 0;
        unsigned char bad[32]; memcpy(bad, leaves[m], 32); bad[0] ^= 1;
        if (merkle_verify_inclusion(m, 8, bad, proof, plen, root8)) tamper_leaf = 1;
        unsigned char bp[MERKLE_MAX_PROOF][32]; memcpy(bp, proof, sizeof bp); bp[0][0] ^= 1;
        if (merkle_verify_inclusion(m, 8, leaves[m], bp, plen, root8)) tamper_proof = 1;
        if (m + 1 < 8 && merkle_verify_inclusion(m + 1, 8, leaves[m], proof, plen, root8)) wrong_idx = 1;
    }
    CHECK(all_incl, "every leaf proves against the root");
    CHECK(!tamper_leaf, "tampered leaf rejected");
    CHECK(!tamper_proof, "tampered proof rejected");
    CHECK(!wrong_idx, "proof bound to its leaf index");

    /* 4. Consistency proof KAT (m=5, n=8) matches reference and verifies. */
    unsigned char cp[MERKLE_MAX_PROOF][32]; size_t clen;
    CHECK(merkle_consistency_proof(leaves, 8, 5, cp, &clen) == 0 && clen == 4, "consistency proof m=5 n=8 built");
    int cons_kat = (clen == 4);
    for (size_t i = 0; i < clen && cons_kat; i++) if (memcmp(cp[i], CONS[i], 32) != 0) cons_kat = 0;
    CHECK(cons_kat, "consistency proof matches reference");
    CHECK(merkle_verify_consistency(5, 8, ROOTS[4], ROOTS[7], CONS, 4) == 1, "verify reference consistency proof");

    /* 5. Every prefix m of an 8-leaf tree is consistent; a rewritten history is not. */
    int all_cons = 1, bad_first = 0, tamper_cons = 0;
    for (size_t m = 1; m <= 8; m++) {
        merkle_consistency_proof(leaves, 8, m, cp, &clen);
        if (!merkle_verify_consistency(m, 8, ROOTS[m - 1], root8, cp, clen)) all_cons = 0;
        /* wrong first root (as if the log rewrote the size-m tree) must fail */
        unsigned char wrongfirst[32]; memcpy(wrongfirst, ROOTS[m - 1], 32); wrongfirst[0] ^= 1;
        if (m < 8 && merkle_verify_consistency(m, 8, wrongfirst, root8, cp, clen)) bad_first = 1;
        if (m < 8 && clen > 0) { unsigned char bc[MERKLE_MAX_PROOF][32]; memcpy(bc, cp, sizeof bc);
            bc[0][0] ^= 1;
            if (merkle_verify_consistency(m, 8, ROOTS[m - 1], root8, bc, clen)) tamper_cons = 1; }
    }
    CHECK(all_cons, "every prefix is consistent with the full tree");
    CHECK(!bad_first, "rewritten prefix root rejected (equivocation caught)");
    CHECK(!tamper_cons, "tampered consistency proof rejected");

    /* 6. A second, different size-8 tree that only shares the size-5 prefix is a valid
     * append; one that DIFFERS in the shared prefix must fail consistency. */
    unsigned char leaves2[8][32]; mk_leaves(leaves2);
    for (int i = 5; i < 8; i++) leaves2[i][0] ^= 0xAA;       /* differ only after the prefix */
    unsigned char root2[32]; merkle_root(leaves2, 8, root2);
    merkle_consistency_proof(leaves2, 8, 5, cp, &clen);
    CHECK(merkle_verify_consistency(5, 8, ROOTS[4], root2, cp, clen) == 1, "diverging suffix still consistent with shared prefix");
    unsigned char leaves3[8][32]; mk_leaves(leaves3); leaves3[2][0] ^= 0xAA;  /* rewrite inside the prefix */
    unsigned char root3[32]; merkle_root(leaves3, 8, root3);
    merkle_consistency_proof(leaves3, 8, 5, cp, &clen);
    CHECK(merkle_verify_consistency(5, 8, ROOTS[4], root3, cp, clen) == 0, "rewritten prefix breaks consistency");

    printf("\n%s\n", fails ? "SOME TESTS FAILED" : "ALL TESTS PASSED");
    return fails ? 1 : 0;
}
